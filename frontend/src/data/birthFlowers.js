export function getBirthFlower(date = new Date()) {
  const month = date.getMonth() + 1
  const day = date.getDate()
  const flowers = birthFlowerData[month]
  if (!flowers) return { flower: '장미', meaning: '사랑', emoji: '🌹', color: '#ef5350' }
  const flower = flowers[day - 1]
  return flower || { flower: '장미', meaning: '사랑', emoji: '🌹', color: '#ef5350' }
}

export function getDateString(date = new Date()) {
  const days = ['일', '월', '화', '수', '목', '금', '토']
  const year = date.getFullYear()
  const month = date.getMonth() + 1
  const day = date.getDate()
  const dow = days[date.getDay()]
  return `${year}년 ${month}월 ${day}일 ${dow}요일`
}
