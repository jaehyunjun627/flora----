export function getTodayBirthFlower() {
  const now = new Date();
  const month = now.getMonth() + 1;
  const day = now.getDate();
  const key = `${month}-${day}`;
  return {
    ...BIRTH_FLOWERS[key],
    month,
    day,
    dateStr: `${month}월 ${day}일`,
  };
}

export function getBirthFlowerByDate(month, day) {
  const key = `${month}-${day}`;
  return BIRTH_FLOWERS[key] ? {
    ...BIRTH_FLOWERS[key],
    month,
    day,
    dateStr: `${month}월 ${day}일`,
  } : null;
}

